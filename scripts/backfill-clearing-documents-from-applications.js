const { PrismaClient } = require('@prisma/client')

const prisma = new PrismaClient()

function roundMoney(value) {
  return Math.round((Number(value ?? 0) + Number.EPSILON) * 100) / 100
}

async function generateNextClearingDocumentNumber(tx) {
  const prefix = 'CLR-'
  const latest = await tx.clearingDocumentHeader.findMany({
    where: { clearingNumber: { startsWith: prefix } },
    select: { clearingNumber: true },
    orderBy: { clearingNumber: 'desc' },
    take: 200,
  })

  const maxSequence = latest.reduce((max, entry) => {
    const match = entry.clearingNumber.match(/^CLR-(\d+)$/i)
    if (!match) return max
    const next = Number.parseInt(match[1], 10)
    return Number.isFinite(next) && next > max ? next : max
  }, 0)

  return `${prefix}${maxSequence + 1}`
}

async function main() {
  const applications = await prisma.openItemApplication.findMany({
    where: {
      applicationType: {
        in: [
          'invoice_receipt_application',
          'bill_payment_application',
          'credit_memo_application',
          'bill_credit_application',
          'customer_refund_application',
          'vendor_refund_application',
        ],
      },
    },
    include: {
      fromOpenItem: true,
      toOpenItem: true,
    },
    orderBy: { createdAt: 'asc' },
  })

  let created = 0
  for (const application of applications) {
    const existing = await prisma.clearingDocumentLine.findFirst({
      where: { openItemApplicationId: application.id },
      select: { id: true },
    })
    if (existing) continue

    const clearingNumber = await generateNextClearingDocumentNumber(prisma)
    await prisma.clearingDocumentHeader.create({
      data: {
        clearingNumber,
        clearingType: application.applicationType,
        status: 'posted',
        subsidiaryId: application.fromOpenItem?.subsidiaryId ?? application.toOpenItem?.subsidiaryId ?? null,
        transactionCurrencyId:
          application.fromOpenItem?.transactionCurrencyId ?? application.toOpenItem?.transactionCurrencyId ?? null,
        localCurrencyId:
          application.fromOpenItem?.localCurrencyId ?? application.toOpenItem?.localCurrencyId ?? null,
        functionalCurrencyId:
          application.fromOpenItem?.functionalCurrencyId ?? application.toOpenItem?.functionalCurrencyId ?? null,
        groupCurrencyId:
          application.fromOpenItem?.groupCurrencyId ?? application.toOpenItem?.groupCurrencyId ?? null,
        clearingDate: application.applicationDate,
        postingDate: application.postingDate ?? null,
        sourceTransactionType: application.settlementTransactionType ?? null,
        sourceTransactionId: application.settlementTransactionId ?? null,
        counterpartyType:
          application.fromOpenItem?.counterpartyType ?? application.toOpenItem?.counterpartyType ?? null,
        counterpartyId:
          application.fromOpenItem?.counterpartyId ?? application.toOpenItem?.counterpartyId ?? null,
        transactionAmount: roundMoney(application.transactionAmount),
        localAmount: application.localAmount == null ? null : roundMoney(application.localAmount),
        functionalAmount: application.functionalAmount == null ? null : roundMoney(application.functionalAmount),
        groupAmount: application.groupAmount == null ? null : roundMoney(application.groupAmount),
        realizedFxLocalAmount:
          application.realizedFxLocalAmount == null ? null : roundMoney(application.realizedFxLocalAmount),
        realizedFxFunctionalAmount:
          application.realizedFxFunctionalAmount == null ? null : roundMoney(application.realizedFxFunctionalAmount),
        realizedFxGroupAmount:
          application.realizedFxGroupAmount == null ? null : roundMoney(application.realizedFxGroupAmount),
        memo: application.memo ?? null,
        autoGenerated: true,
        automationSource: application.settlementTransactionType === 'vendor-refund' || application.settlementTransactionType === 'customer-refund'
          ? `${application.settlementTransactionType}-posting`
          : 'validation_pack',
        createdById: application.createdById ?? null,
        lines: {
          create: [
            {
              lineNumber: 1,
              lineRole: 'source',
              fromOpenItemId: application.fromOpenItemId,
              sourceTransactionType: application.fromOpenItem?.sourceTransactionType ?? null,
              sourceTransactionId: application.fromOpenItem?.sourceTransactionId ?? null,
              sourceTransactionLineId: application.fromOpenItem?.sourceTransactionLineId ?? null,
              settlementTransactionType: application.settlementTransactionType ?? null,
              settlementTransactionId: application.settlementTransactionId ?? null,
              transactionAmount: roundMoney(application.transactionAmount),
              localAmount: application.localAmount == null ? null : roundMoney(application.localAmount),
              functionalAmount: application.functionalAmount == null ? null : roundMoney(application.functionalAmount),
              groupAmount: application.groupAmount == null ? null : roundMoney(application.groupAmount),
              realizedFxLocalAmount:
                application.realizedFxLocalAmount == null ? null : roundMoney(application.realizedFxLocalAmount),
              realizedFxFunctionalAmount:
                application.realizedFxFunctionalAmount == null ? null : roundMoney(application.realizedFxFunctionalAmount),
              realizedFxGroupAmount:
                application.realizedFxGroupAmount == null ? null : roundMoney(application.realizedFxGroupAmount),
              openItemApplicationId: application.id,
              memo: application.memo ?? null,
            },
            ...(application.toOpenItemId
              ? [{
                  lineNumber: 2,
                  lineRole: 'target',
                  toOpenItemId: application.toOpenItemId,
                  sourceTransactionType: application.toOpenItem?.sourceTransactionType ?? null,
                  sourceTransactionId: application.toOpenItem?.sourceTransactionId ?? null,
                  sourceTransactionLineId: application.toOpenItem?.sourceTransactionLineId ?? null,
                  settlementTransactionType: application.settlementTransactionType ?? null,
                  settlementTransactionId: application.settlementTransactionId ?? null,
                  transactionAmount: roundMoney(application.transactionAmount),
                  localAmount: application.localAmount == null ? null : roundMoney(application.localAmount),
                  functionalAmount: application.functionalAmount == null ? null : roundMoney(application.functionalAmount),
                  groupAmount: application.groupAmount == null ? null : roundMoney(application.groupAmount),
                  realizedFxLocalAmount:
                    application.realizedFxLocalAmount == null ? null : roundMoney(application.realizedFxLocalAmount),
                  realizedFxFunctionalAmount:
                    application.realizedFxFunctionalAmount == null ? null : roundMoney(application.realizedFxFunctionalAmount),
                  realizedFxGroupAmount:
                    application.realizedFxGroupAmount == null ? null : roundMoney(application.realizedFxGroupAmount),
                  openItemApplicationId: application.id,
                  memo: application.memo ?? null,
                }]
              : []),
          ],
        },
      },
    })
    created += 1
  }

  console.log(JSON.stringify({ scanned: applications.length, created }, null, 2))
}

main()
  .catch((error) => {
    console.error(error)
    process.exitCode = 1
  })
  .finally(async () => {
    await prisma.$disconnect()
  })

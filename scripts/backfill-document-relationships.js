const { PrismaClient } = require('@prisma/client')

const prisma = new PrismaClient()

async function syncAutoRelationshipsForSource({
  sourceRecordType,
  sourceRecordId,
  relationshipType,
  automationSource,
  targets,
}) {
  const seen = new Set()
  const dedupedTargets = targets.filter((target) => {
    if (!target.recordType || !target.recordId) return false
    const key = `${target.recordType}:${target.recordId}`
    if (seen.has(key)) return false
    seen.add(key)
    return true
  })

  await prisma.documentRelationship.deleteMany({
    where: {
      sourceRecordType,
      sourceRecordId,
      relationshipType,
      autoGenerated: true,
      automationSource,
    },
  })

  if (!dedupedTargets.length) return

  await prisma.documentRelationship.createMany({
    data: dedupedTargets.map((target) => ({
      sourceRecordType,
      sourceRecordId,
      targetRecordType: target.recordType,
      targetRecordId: target.recordId,
      relationshipType,
      autoGenerated: true,
      automationSource,
    })),
  })
}

async function main() {
  const [billPayments, invoiceReceipts, journals] = await Promise.all([
    prisma.billPayment.findMany({
      select: {
        id: true,
        billId: true,
        applications: {
          select: {
            billId: true,
          },
        },
      },
    }),
    prisma.cashReceipt.findMany({
      select: {
        id: true,
        invoiceId: true,
        applications: {
          select: {
            invoiceId: true,
          },
        },
      },
    }),
    prisma.journalEntry.findMany({
      where: {
        reversesJournalEntryId: {
          not: null,
        },
      },
      select: {
        id: true,
        reversesJournalEntryId: true,
      },
    }),
  ])

  for (const payment of billPayments) {
    const targetBillIds = Array.from(
      new Set(
        [payment.billId, ...payment.applications.map((application) => application.billId)].filter(Boolean),
      ),
    )

    await syncAutoRelationshipsForSource({
      sourceRecordType: 'bill-payment',
      sourceRecordId: payment.id,
      relationshipType: 'settles',
      automationSource: 'bill-payment-applications',
      targets: targetBillIds.map((billId) => ({
        recordType: 'bill',
        recordId: billId,
      })),
    })
  }

  for (const receipt of invoiceReceipts) {
    const targetInvoiceIds = Array.from(
      new Set(
        [receipt.invoiceId, ...receipt.applications.map((application) => application.invoiceId)].filter(Boolean),
      ),
    )

    await syncAutoRelationshipsForSource({
      sourceRecordType: 'invoice-receipt',
      sourceRecordId: receipt.id,
      relationshipType: 'settles',
      automationSource: 'invoice-receipt-applications',
      targets: targetInvoiceIds.map((invoiceId) => ({
        recordType: 'invoice',
        recordId: invoiceId,
      })),
    })
  }

  for (const journal of journals) {
    await syncAutoRelationshipsForSource({
      sourceRecordType: 'journal-entry',
      sourceRecordId: journal.id,
      relationshipType: 'reverses',
      automationSource: 'journal-reversal',
      targets: journal.reversesJournalEntryId
        ? [{ recordType: 'journal-entry', recordId: journal.reversesJournalEntryId }]
        : [],
    })
  }

  console.log(
    `Backfilled relationships for ${billPayments.length} bill payments, ${invoiceReceipts.length} invoice receipts, and ${journals.length} reversing journals.`,
  )
}

main()
  .catch((error) => {
    console.error(error)
    process.exit(1)
  })
  .finally(async () => {
    await prisma.$disconnect()
  })
